function escapeHtml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function highlight(value) {
  const safe = escapeHtml(value);
  const query = searchInput.value.trim();
  if (!query) return safe;
  const escaped = query.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return safe.replace(new RegExp(escaped, "gi"), (match) => `<mark>${match}</mark>`);
}

function sectionMatches(section, query) {
  if (!query) return true;
  const haystack = `${section.heading} ${section.source} ${section.bullets.join(" ")}`.toLowerCase();
  return haystack.includes(query.toLowerCase());
}

function renderNav() {
  chapterNav.innerHTML = "";
  chapters.forEach((chapter, index) => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = `chapter-btn ${index === state.chapterIndex ? "active" : ""} ${state.completed.has(chapter.id) ? "completed" : ""}`;
    button.innerHTML = `
      <span class="chapter-num">${chapter.number}</span>
      <span class="chapter-name">${escapeHtml(chapter.title)}</span>
      <span class="done-dot" aria-hidden="true"></span>
    `;
    button.addEventListener("click", () => {
      state.chapterIndex = index;
      state.flashIndex = 0;
      state.flashRevealed = false;
      state.quizIndex = 0;
      state.quizScore = 0;
      state.quizAnswered = false;
      render();
    });
    chapterNav.appendChild(button);
  });
}

function currentChapter() {
  return chapters[state.chapterIndex];
}

function renderHeader() {
  const chapter = currentChapter();
  chapterSource.textContent = chapter.source;
  chapterTitle.textContent = chapter.title;
  chapterSummary.textContent = chapter.summary;
  markCompleteBtn.textContent = state.completed.has(chapter.id) ? "Chapter studied" : "Mark chapter studied";
}

function renderNotes() {
  const chapter = currentChapter();
  const query = searchInput.value.trim();
  const sections = chapter.sections.filter((section) => sectionMatches(section, query));
  if (!sections.length) {
    content.innerHTML = `<div class="empty-state">No notes matched "${escapeHtml(query)}" in this chapter.</div>`;
    return;
  }
  content.innerHTML = `<div class="content-grid"></div>`;
  const grid = content.querySelector(".content-grid");
  sections.forEach((section) => {
    const card = document.createElement("article");
    card.className = "note-card";
    card.innerHTML = `
      <span class="source">${highlight(section.source)}</span>
      <h3>${highlight(section.heading)}</h3>
      <ul>${section.bullets.map((item) => `<li>${highlight(item)}</li>`).join("")}</ul>
    `;
    grid.appendChild(card);
  });
}

