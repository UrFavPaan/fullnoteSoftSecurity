function renderFlashcards() {
  const chapter = currentChapter();
  const deck = chapter.flashcards;
  const card = deck[state.flashIndex % deck.length];
  content.innerHTML = `
    <div class="flashcard ${state.flashRevealed ? "revealed" : ""}">
      <div class="source">Card ${state.flashIndex + 1} of ${deck.length}</div>
      <div class="question">${escapeHtml(card[0])}</div>
      <div class="answer">${escapeHtml(card[1])}</div>
      <div class="card-actions">
        <button class="tool-btn" id="prevCard" type="button">Previous</button>
        <button class="tool-btn" id="revealCard" type="button">${state.flashRevealed ? "Hide answer" : "Reveal answer"}</button>
        <button class="tool-btn" id="nextCard" type="button">Next</button>
      </div>
    </div>
  `;
  document.querySelector("#prevCard").addEventListener("click", () => {
    state.flashIndex = (state.flashIndex - 1 + deck.length) % deck.length;
    state.flashRevealed = false;
    renderFlashcards();
  });
  document.querySelector("#revealCard").addEventListener("click", () => {
    state.flashRevealed = !state.flashRevealed;
    renderFlashcards();
  });
  document.querySelector("#nextCard").addEventListener("click", () => {
    state.flashIndex = (state.flashIndex + 1) % deck.length;
    state.flashRevealed = false;
    renderFlashcards();
  });
}

function renderQuiz() {
  const chapter = currentChapter();
  const quiz = chapter.quiz;
  const item = quiz[state.quizIndex % quiz.length];
  content.innerHTML = `
    <div class="quiz-card">
      <span class="source">Question ${state.quizIndex + 1} of ${quiz.length} | Score ${state.quizScore}</span>
      <h3>${escapeHtml(item.question)}</h3>
      <div class="option-grid">
        ${item.options.map((option, index) => `<button class="option-btn" data-index="${index}" type="button">${escapeHtml(option)}</button>`).join("")}
      </div>
      <div class="quiz-feedback" id="quizFeedback"></div>
      <div class="quiz-actions">
        <button class="tool-btn" id="nextQuestion" type="button">Next question</button>
        <button class="tool-btn" id="resetQuiz" type="button">Reset quiz</button>
      </div>
    </div>
  `;
  document.querySelectorAll(".option-btn").forEach((button) => {
    button.addEventListener("click", () => {
      if (state.quizAnswered) return;
      state.quizAnswered = true;
      const picked = Number(button.dataset.index);
      const correct = picked === item.answer;
      if (correct) state.quizScore += 1;
      document.querySelectorAll(".option-btn").forEach((optionButton) => {
        const isAnswer = Number(optionButton.dataset.index) === item.answer;
        optionButton.classList.toggle("correct", isAnswer);
        optionButton.classList.toggle("wrong", Number(optionButton.dataset.index) === picked && !correct);
      });
      document.querySelector("#quizFeedback").textContent = `${correct ? "Correct." : "Not quite."} ${item.explain}`;
    });
  });
  document.querySelector("#nextQuestion").addEventListener("click", () => {
    state.quizIndex = (state.quizIndex + 1) % quiz.length;
    state.quizAnswered = false;
    renderQuiz();
  });
  document.querySelector("#resetQuiz").addEventListener("click", () => {
    state.quizIndex = 0;
    state.quizScore = 0;
    state.quizAnswered = false;
    renderQuiz();
  });
}

function riskLabel(score) {
  if (score >= 180) return "High";
  if (score >= 75) return "Medium";
  return "Low";
}

